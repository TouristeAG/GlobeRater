#!/usr/bin/env python3
"""Writes res/values*/strings.xml from tools/strings_en.py and tools/i18n/<lang>.py.
Run from the repo root:  python3 tools/gen_strings.py
"""
import importlib.util, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, '..', 'app', 'src', 'main', 'res')
sys.path.insert(0, HERE)
from strings_en import EN

# language file -> Android resource qualifier
QUALIFIERS = {'fr': 'fr', 'es': 'es', 'pt': 'pt', 'de': 'de', 'it': 'it', 'nl': 'nl', 'ru': 'ru', 'tr': 'tr',
              'ar': 'ar', 'hi': 'hi', 'zh': 'zh-rCN', 'ja': 'ja', 'ko': 'ko', 'id': 'in'}
UNTRANSLATABLE = {'app_name', 'place_role_label', 'settings_header_right', 'material_you', 'wx_unknown'}
FORMAT = re.compile(r'%(\d+\$)?[-#+ 0,(]*\d*(\.\d+)?[sdf]')

def esc(text):
    t = text.replace('\\', '\\\\').replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    t = t.replace("'", "\\'").replace('"', '\\"').replace('\n', '\\n')
    if t[:1] in '@?':
        t = '\\' + t
    return t

def write(path, entries, header):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f'<!-- {header} -->', '<resources>']
    for key, value in entries:
        extra = ' translatable="false"' if key in UNTRANSLATABLE and 'values/' in path else ''
        fmt = ' formatted="false"' if '%' in value and not FORMAT.search(value) else ''
        lines.append(f'    <string name="{key}"{extra}{fmt}>{esc(value)}</string>')
    lines += ['</resources>', '']
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', encoding='utf-8').write('\n'.join(lines))

def args(s):
    return sorted(m.group(0)[-1] + (m.group(1) or '') for m in FORMAT.finditer(s.replace('%%', '')))

write(os.path.join(RES, 'values', 'strings.xml'), EN.items(), 'Generated by tools/gen_strings.py from tools/strings_en.py')
problems = 0
for lang, q in QUALIFIERS.items():
    spec = importlib.util.spec_from_file_location(lang, os.path.join(HERE, 'i18n', f'{lang}.py'))
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    T = mod.T
    unknown = sorted(set(T) - set(EN))
    missing = sorted(k for k in EN if k not in T and k not in UNTRANSLATABLE and EN[k] not in ('—',))
    bad = [k for k in T if k in EN and args(T[k]) != args(EN[k])]
    if unknown or missing or bad:
        problems += 1
        print(f'{lang}: unknown={unknown} missing={missing} format-mismatch={bad}')
    entries = [(k, T[k]) for k in EN if k in T and k not in UNTRANSLATABLE]
    write(os.path.join(RES, f'values-{q}', 'strings.xml'), entries, f'Generated by tools/gen_strings.py from tools/i18n/{lang}.py')
print('languages:', 'en +', len(QUALIFIERS), '| problems:', problems)
