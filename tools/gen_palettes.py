#!/usr/bin/env python3
"""Generates widget palette resources (colors light/dark, drawables) and WidgetPalettes.kt.
Run from the repo root:  python3 tools/gen_palettes.py
"""
import os
ROOT = os.path.join(os.path.dirname(__file__), '..', 'app', 'src', 'main')
RES = os.path.join(ROOT, 'res')
KT = os.path.join(ROOT, 'java', 'com', 'example', 'currencywidget', 'widget', 'WidgetPalettes.kt')

ROLES = ['bg', 'on_bg', 'muted', 'key', 'accent', 'on_accent', 'line', 'fill', 'container']
# id: (display name, light{role}, dark{role})
def mix(a, b, t):
    """a blended toward b by t (0..1)."""
    a = [int(a[i:i+2], 16) for i in (1, 3, 5)]; b = [int(b[i:i+2], 16) for i in (1, 3, 5)]
    return '#' + ''.join(f'{round(x + (y - x) * t):02X}' for x, y in zip(a, b))

def p(bg, on_bg, muted, key, accent, on_accent, line):
    # fill = the rising "water level" of the budget background: accent diluted in bg.
    fill = mix(bg, accent, 0.22) if not bg.startswith('system') else None
    # container = background of the original ("classic") widget design: a light tint.
    container = mix(bg, accent, 0.10) if not bg.startswith('system') else None
    return dict(zip(ROLES, [bg, on_bg, muted, key, accent, on_accent, line, fill, container]))

